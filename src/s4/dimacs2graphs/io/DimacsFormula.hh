/**
 * @file DimacsFormula.hh
 * @brief In-memory DIMACS CNF formula with its name table
 *
 * Reads the clauses and every comment style that carries information about
 * variables (R-OUT-02, R-UVL-01, R-UVL-04, R-PIPE-01 step 1):
 *
 * | Comment                                   | Meaning                                  |
 * |-------------------------------------------|------------------------------------------|
 * | `c <n> <name…>`                           | name of variable n (may contain spaces)  |
 * | `c aux <n> <kind>`                        | n is auxiliary (`tseitin` or `chain`)    |
 * | `c root <n>`                              | n is the root feature (uvl2dimacs 2.0)   |
 * | `c abstract <n>`                          | n is an abstract feature (uvl2dimacs 2.0)|
 * | `c generated-by uvl2dimacs <v> mode=<m>`  | header written by uvl2dimacs 2.0         |
 * | `c <n> aux_<k>[_…] (auxiliary)`           | auxiliary variable written by 1.x        |
 */

#ifndef DIMACS2GRAPHS_DIMACS_FORMULA_HH
#define DIMACS2GRAPHS_DIMACS_FORMULA_HH

#include <cstdint>
#include <iosfwd>
#include <string>
#include <vector>

namespace dimacs2graphs {

/// Kind of auxiliary variable declared by a reserved `c aux` comment.
enum class AuxKind : std::uint8_t { None, Tseitin, Chain };

/**
 * @brief A CNF formula with per-variable metadata. Variables are 1-based;
 * every per-variable vector has size num_vars + 1 (index 0 unused).
 */
struct DimacsFormula {
    std::string path;                       ///< File the formula was read from
    int num_vars = 0;                       ///< max(p-line count, largest variable used or named)
    int declared_vars = 0;                  ///< Variables declared in the p line
    int declared_clauses = 0;               ///< Clauses declared in the p line
    std::vector<std::vector<int>> clauses;  ///< Clauses as DIMACS literals

    std::vector<std::string> names;         ///< Name of each variable ("" if none)
    std::vector<AuxKind> aux;               ///< From `c aux` (or 1.x "(auxiliary)" names)
    std::vector<char> is_root;              ///< From `c root`
    std::vector<char> is_abstract;          ///< From `c abstract`

    bool uvl_header = false;                ///< `c generated-by uvl2dimacs` present
    std::string uvl_version;                ///< Version in that header
    std::string uvl_mode;                   ///< `straightforward` or `tseitin`
    bool legacy_uvl_header = false;         ///< 1.x header `c Generated by UVL2Dimacs`

    bool has_name(int v) const { return v >= 1 && v <= num_vars && !names[v].empty(); }

    /// Adds a fresh variable (used by the formula transformations); returns its number.
    int add_variable(const std::string& name);

    /// Resizes every per-variable vector to n + 1 entries.
    void resize(int n);
};

/**
 * @brief Reads a DIMACS file.
 * @param path  File path, used as given (any extension; fixes D7)
 * @param out   Formula
 * @param error Message on failure: what, where (file and line) and what to do
 * @return true on success. Failure is an input error (exit code 2).
 *
 * Duplicate variable names are reported as an error (R-ERR, code 2).
 */
bool read_dimacs(const std::string& path, DimacsFormula& out, std::string& error);

/// Base name of a path: file name without directory and without its last extension.
std::string path_stem(const std::string& path);

/// Directory of a path, or "." when it has none.
std::string path_dir(const std::string& path);

/**
 * @brief Whether a file or a directory exists, without throwing.
 *
 * `std::filesystem::exists` throws when a path cannot be examined (a directory on it that may not be read, a
 * name too long). This function returns false instead and sets `error` to the reason and what to do (an input
 * error, exit code 2); `error` is empty when the path does not exist.
 */
bool path_exists(const std::string& path, std::string& error);

/**
 * @brief The message for a file that could not be read to its end (an input error, exit code 2).
 *
 * `std::getline` and the other stream functions report an error of the system (an I/O error of the disk, a
 * network share that goes away) or of the allocator only through the bad state of the stream, which a loop on
 * `getline` takes for the end of the file. Every reader checks `bad()` after its loop and gives this message.
 * @param path       The file
 * @param lines_read Lines read before the error (0: not counted)
 */
std::string read_error(const std::string& path, long lines_read);

/**
 * @brief Reads the rest of an open file into `text`, telling a read error from the end of the file.
 * @return false, with `error` set by read_error(), if the file could not be read to its end
 */
bool read_text(std::istream& in, const std::string& path, std::string& text, std::string& error);

} // namespace dimacs2graphs

#endif
