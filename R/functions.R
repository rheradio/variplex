# The parameters of a function as one would type them: a parameter without a
# default by its name, one with a default as name = value (a choice among values
# shows its first one, the default). Read from the definition itself.
.vp_parameters <- function(fn) {
  a <- formals(get(fn, mode = "function", envir = asNamespace("variplex")))
  vapply(
    names(a),
    function(p) {
      if (identical(a[[p]], quote(expr = ))) {
        return(p)
      } # no default
      d <- a[[p]]
      if (is.call(d) && identical(d[[1]], as.name("c"))) {
        d <- d[[2]]
      } # c("a", "b"): the default is the first
      paste(p, "=", paste(deparse(d, width.cutoff = 500L), collapse = " "))
    },
    ""
  ) |>
    paste(collapse = ", ")
}
